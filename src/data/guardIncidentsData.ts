export type IncidentSeverity = 'Critical' | 'High' | 'Medium' | 'Low';
export type IncidentStatus = 'Open' | 'Under Investigation' | 'Resolved' | 'Closed';
export type MovementDirection = 'Inward' | 'Outward' | 'Not Applicable';

export interface IncidentEvidenceAttachment {
  id: string;
  filename: string;
  size: string;
  type: 'image' | 'pdf' | 'doc';
  label: string;
  previewColor?: string;
  thumbnailUrl?: string;
}

export interface IncidentTimelineEvent {
  id: string;
  timestamp: string; // e.g. "May 24, 2026, 11:24 AM"
  event: string;
  actor: string;
  actorRole: string;
  note?: string;
}

export interface SecurityIncidentRecord {
  id: string; // e.g. INC-2026-0089
  title: string;
  type: string;
  severity: IncidentSeverity;
  status: IncidentStatus;
  date: string; // YYYY-MM-DD
  time: string; // HH:MM
  formattedDateTime: string;
  checkpoint: string; // e.g. "Gate-01A Main Gate"
  locationDetail: string; // e.g. "Inspection Bay 02 / Lane 02"
  relatedPassId?: string | null;
  relatedAssetId?: string | null;
  direction: MovementDirection;
  description: string;
  immediateAction: string;
  witnessInfo?: string | null;
  evidenceAttachments: IncidentEvidenceAttachment[];
  timeline: IncidentTimelineEvent[];
  reportedBy: string;
  reportedByBadge: string;
  canAppendObservation: boolean; // true for Open / Under Investigation
}

